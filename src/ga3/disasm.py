"""m68000 disassembler for Mega Drive ROMs (Capstone). Optional extra ``[disasm]``."""

from __future__ import annotations

Row = tuple[int, bytes, str, str]


def _engine():
    try:
        import capstone
    except ImportError as exc:  # pragma: no cover
        raise RuntimeError("capstone is required: pip install 'ga3[disasm]'") from exc
    md = capstone.Cs(capstone.CS_ARCH_M68K, capstone.CS_MODE_M68K_000)
    md.detail = False
    return md


def disasm(data: bytes, start: int, count: int = 40, end: int | None = None) -> list[Row]:
    """Disassemble, stepping over invalid words.

    Capstone stops at the first opcode it cannot decode, and ROMs keep data
    tables between routines -- so on failure we emit a ``.word`` and advance
    by one word.
    """
    md = _engine()
    limit = end if end is not None else min(len(data), start + count * 12)
    out: list[Row] = []
    pc = start
    while pc < limit and (end is not None or len(out) < count):
        got = False
        for ins in md.disasm(data[pc:limit], pc):
            out.append((ins.address, bytes(ins.bytes), ins.mnemonic, ins.op_str))
            pc = ins.address + ins.size
            got = True
            if end is None and len(out) >= count:
                break
        if not got:
            word = data[pc : pc + 2]
            out.append((pc, bytes(word), ".word", "$%04X" % int.from_bytes(word, "big")))
            pc += 2
    return out


def fmt(rows: list[Row]) -> str:
    return "\n".join("%06X  %-20s %-8s %s" % (a, raw.hex(" "), mn, ops) for a, raw, mn, ops in rows)


def listing(data: bytes, start: int, end: int, title: str) -> str:
    """A whole-region listing for ``assets/code/asm/*.s`` (generated, not hand-edited)."""
    head = [
        f"; {title}: {start:06X}-{end:06X} ({end - start} bytes)",
        "; Generated by `ga3 asm` with Capstone (CS_MODE_M68K_000). Do not edit:",
        "; the source of truth is the ROM byte range described in rom_map.yml.",
        "; Data tables between routines appear as .word; labels are not recovered.",
        "",
    ]
    return "\n".join(head) + fmt(disasm(data, start, 0, end=end)) + "\n"
